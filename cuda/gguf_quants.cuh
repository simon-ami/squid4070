namespace squid::gguf {

static_assert(std::endian::native == std::endian::little);
static_assert(sizeof(float) == 4 && std::numeric_limits<float>::is_iec559);

enum class Type : uint32_t {
    f32 = 0, q8_0 = 8, q4_k = 12, q5_k = 13, q6_k = 14,
    iq2_xxs = 16, iq2_xs = 17, iq3_xxs = 18, iq1_s = 19,
    iq4_nl = 20, iq2_s = 22, iq4_xs = 23, bf16 = 30, nvfp4 = 40, q2_0 = 42,
};

// FP16 and BF16 fields contain IEEE binary16 and bfloat16 bits, respectively.
struct block_q2_0 { uint16_t d; uint8_t qs[16]; };
struct block_nvfp4 { uint8_t d[4]; uint8_t qs[32]; };
struct block_iq2_xxs { uint16_t d; uint16_t qs[32]; };
struct block_iq2_xs { uint16_t d; uint16_t qs[32]; uint8_t scales[8]; };
struct block_iq2_s { uint16_t d; uint8_t qs[64]; uint8_t qh[8]; uint8_t scales[8]; };
struct block_iq1_s { uint16_t d; uint8_t qs[32]; uint16_t qh[8]; };
struct block_iq4_nl { uint16_t d; uint8_t qs[16]; };
struct block_iq4_xs { uint16_t d; uint16_t scales_h; uint8_t scales_l[4]; uint8_t qs[128]; };
struct block_iq3_xxs { uint16_t d; uint8_t qs[96]; };
struct block_q8_0 { uint16_t d; int8_t qs[32]; };

struct block_q6_k {
    uint8_t ql[128];
    uint8_t qh[64];
    int8_t scales[16];
    uint16_t d;
};

struct block_q5_k {
    uint16_t d;
    uint16_t dmin;
    uint8_t scales[12];
    uint8_t qh[32];
    uint8_t qs[128];
};

struct block_q4_k {
    uint16_t d;
    uint16_t dmin;
    uint8_t scales[12];
    uint8_t qs[128];
};

struct block_bf16 { uint16_t bits; };
struct block_f32 { float value; };

template <class Block> struct quant_traits;

#define SQUID_GGUF_TRAITS(name, count, bytes)               \
    static_assert(sizeof(block_##name) == bytes);           \
    template <> struct quant_traits<block_##name> {         \
        static constexpr int values = count;                \
        static constexpr Type type = Type::name;            \
    }

