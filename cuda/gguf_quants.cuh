SQUID_GGUF_INLINE float float_from_bits(uint32_t bits) {
#if defined(__CUDA_ARCH__)
    return __uint_as_float(bits);
#else
    return std::bit_cast<float>(bits);
#endif
}

SQUID_GGUF_INLINE float fp16(uint16_t bits) {
    const uint32_t sign = (uint32_t(bits) & 0x8000) << 16;
    const uint32_t exponent = (bits >> 10) & 31;
    const uint32_t fraction = bits & 1023;
    if (exponent == 0) {
        const float magnitude = float(fraction) * 0x1p-24f;
        return sign ? -magnitude : magnitude;
    }
    const uint32_t float_exponent = exponent == 31 ? 255 : exponent + 112;
    return float_from_bits(sign | (float_exponent << 23) | (fraction << 13));
}

// ggml_ue4m3_to_fp32 returns half the decoded scale because kvalues_fp4 is doubled.
SQUID_GGUF_INLINE float ue4m3_half(uint8_t bits) {
    if (bits == 0x7f) {
        return 0.0f;
    }
    const unsigned exponent = bits >> 3;
    const unsigned mantissa = bits & 7;
    if (exponent == 0) {
        return float(mantissa) * 0x1p-10f;
    }
    return float_from_bits(((exponent + 119) << 23) | (mantissa << 20));
}

SQUID_GGUF_INLINE int nibble(uint8_t bits, int half) {
    return (bits >> (4 * half)) & 15;
}

SQUID_GGUF_INLINE float dequant_iq4_nl(uint16_t d, uint8_t packed, int half) {
    return fp16(d) * float(kvalues_iq4nl[nibble(packed, half)]);
}

template <class UInt>
SQUID_GGUF_INLINE int grid_byte(UInt grid, int lane) {
    return int((grid >> (8 * lane)) & 255);
}

SQUID_GGUF_INLINE float iq_signed(float value, uint8_t signs, int lane) {
    return value * ((signs & kmask_iq2xs[lane]) ? -1.0f : 1.0f);
}

SQUID_GGUF_INLINE uint32_t read_u32_le(const uint8_t* bytes) {
    return uint32_t(bytes[0]) | (uint32_t(bytes[1]) << 8) |
           (uint32_t(bytes[2]) << 16) | (uint32_t(bytes[3]) << 24);
}

template <class Block>
SQUID_GGUF_INLINE float dequant_k_affine(const Block& b, int lane, int quant) {
    const int group = lane / 32;
    int scale;
    int minimum;
    if (group < 4) {
        scale = b.scales[group] & 63;
        minimum = b.scales[group + 4] & 63;
    } else {
        scale = (b.scales[group + 4] & 15) | ((b.scales[group - 4] >> 6) << 4);
        minimum = (b.scales[group + 4] >> 4) | ((b.scales[group] >> 6) << 4);
    }
    const float d = fp16(b.d) * float(scale);
    const float m = fp16(b.dmin) * float(minimum);
#if defined(__CUDA_ARCH__)
    return __fsub_rn(__fmul_rn(d, float(quant)), m);
#else
    return d * float(quant) - m;
#endif
}

