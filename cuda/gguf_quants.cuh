// Decode one value in a block. The caller supplies a lane in [0, quant_traits<Block>::values).
SQUID_GGUF_INLINE float dequant_value(const block_q2_0& b, int lane) {
    const int quant = (b.qs[lane / 4] >> (2 * (lane % 4))) & 3;
    return float(quant - 1) * detail::fp16(b.d);
}

SQUID_GGUF_INLINE float dequant_value(const block_nvfp4& b, int lane) {
    const int group = lane / 16;
    const int within_group = lane % 16;
    const int code = detail::nibble(b.qs[8 * group + within_group % 8], within_group / 8);
    return float(detail::kvalues_fp4[code]) * detail::ue4m3_half(b.d[group]);
}

SQUID_GGUF_INLINE float dequant_value(const block_iq2_xxs& b, int lane) {
    const int group = lane / 32;
    const int chunk = (lane % 32) / 8;
    const int sample = lane % 8;
    const auto* packed = b.qs + 4 * group;
    const int grid_index = (packed[chunk / 2] >> (8 * (chunk % 2))) & 255;
    const uint32_t flags = uint32_t(packed[2]) | (uint32_t(packed[3]) << 16);
    const uint8_t signs = detail::ksigns_iq2xs[(flags >> (7 * chunk)) & 127];
    const float d = detail::fp16(b.d) * (0.5f + float(flags >> 28)) * 0.25f;
    return detail::iq_signed(d * detail::grid_byte(detail::iq2xxs_grid[grid_index], sample), signs, sample);
}

SQUID_GGUF_INLINE float dequant_value(const block_iq2_xs& b, int lane) {
    const int sample = lane % 8;
    const uint16_t packed = b.qs[lane / 8];
    const int scale = detail::nibble(b.scales[lane / 32], (lane / 16) % 2);
    const float d = detail::fp16(b.d) * (0.5f + float(scale)) * 0.25f;
    const int q = detail::grid_byte(detail::iq2xs_grid[packed & 511], sample);
    return detail::iq_signed(d * q, detail::ksigns_iq2xs[packed >> 9], sample);
}

SQUID_GGUF_INLINE float dequant_value(const block_iq2_s& b, int lane) {
    const int group = lane / 32;
    const int chunk = lane / 8;
    const int sample = lane % 8;
    const int index = b.qs[chunk] | (((b.qh[group] >> (2 * (chunk % 4))) & 3) << 8);
    const int scale = detail::nibble(b.scales[group], (lane / 16) % 2);
    const float d = detail::fp16(b.d) * (0.5f + float(scale)) * 0.25f;
    const int q = detail::grid_byte(detail::iq2s_grid[index], sample);
    return detail::iq_signed(d * q, b.qs[32 + chunk], sample);
}

SQUID_GGUF_INLINE float dequant_value(const block_iq1_s& b, int lane) {
    const int chunk = lane / 8;
    const uint16_t flags = b.qh[lane / 32];
    const int index = b.qs[chunk] | (((flags >> (3 * (chunk % 4))) & 7) << 8);
    const int raw = detail::grid_byte(detail::iq1s_grid[index], lane % 8);
    const int q = (raw ^ 128) - 128;
    const float offset = (flags & 0x8000) ? -0.125f : 0.125f;
    const float d = detail::fp16(b.d) * float(2 * ((flags >> 12) & 7) + 1);
    return d * (float(q) + offset);
}

SQUID_GGUF_INLINE float dequant_value(const block_iq4_nl& b, int lane) {
    return detail::dequant_iq4_nl(b.d, b.qs[lane % 16], lane / 16);
}

SQUID_GGUF_INLINE float dequant_value(const block_iq4_xs& b, int lane) {
    const int group = lane / 32;
    const int scale = detail::nibble(b.scales_l[group / 2], group % 2) |
                      (((b.scales_h >> (2 * group)) & 3) << 4);
    const int index = detail::nibble(b.qs[group * 16 + lane % 16], (lane / 16) % 2);
    return (detail::fp16(b.d) * float(scale - 32)) * float(detail::kvalues_iq4nl[index]);
}

SQUID_GGUF_INLINE float dequant_value(const block_iq3_xxs& b, int lane) {
    const int sample = lane % 8;
    const uint32_t flags = detail::read_u32_le(b.qs + 64 + 4 * (lane / 32));
    const uint8_t signs = detail::ksigns_iq2xs[(flags >> (7 * ((lane / 8) % 4))) & 127];
    const float d = detail::fp16(b.d) * (0.5f + float(flags >> 28)) * 0.5f;
    const int q = detail::grid_byte(detail::iq3xxs_grid[b.qs[lane / 4]], lane % 4);
    return detail::iq_signed(d * q, signs, sample);
}

SQUID_GGUF_INLINE float dequant_value(const block_q8_0& b, int lane) {
    return detail::fp16(b.d) * float(b.qs[lane]);
}

SQUID_GGUF_INLINE float dequant_value(const block_q6_k& b, int lane) {
    const int half = lane / 128;
    const int group = (lane % 128) / 32;
    const int pos = lane % 32;
    const int low = detail::nibble(b.ql[64 * half + 32 * (group % 2) + pos], group / 2);
    const int high = (b.qh[32 * half + pos] >> (2 * group)) & 3;
    const int quant = (low | (high << 4)) - 32;
    return (detail::fp16(b.d) * float(b.scales[lane / 16])) * float(quant);
}

SQUID_GGUF_INLINE float dequant_value(const block_q5_k& b, int lane) {
    const int low = detail::nibble(b.qs[32 * (lane / 64) + lane % 32], (lane / 32) % 2);
    const int high = (b.qh[lane % 32] >> (lane / 32)) & 1;
    return detail::dequant_k_affine(b, lane, low | (high << 4));
}

SQUID_GGUF_INLINE float dequant_value(const block_q4_k& b, int lane) {
    const int quant = detail::nibble(b.qs[32 * (lane / 64) + lane % 32], (lane / 32) % 2);
    return detail::dequant_k_affine(b, lane, quant);
}

SQUID_GGUF_INLINE float dequant_value(const block_bf16& b, int) {
    return detail::float_from_bits(uint32_t(b.bits) << 16);
}

SQUID_GGUF_INLINE float dequant_value(const block_f32& b, int) {
    return b.value;
}

// Dequantize complete blocks into F32. count is the number of output values.
template <class Block>
SQUID_GGUF_INLINE void dequant_row(const Block* src, float* dst, std::size_t count) {
    constexpr int width = quant_traits<Block>::values;
    assert(count % width == 0);
    for (std::size_t block = 0; block < count / width; ++block) {
        for (int lane = 0; lane < width; ++lane) {
            dst[block * width + lane] = dequant_value(src[block], lane);
        }
    }
}

